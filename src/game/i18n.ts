export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function t(locale: AppLocale, key: TranslationKey): string {
  return TRANSLATIONS[locale]?.[key] ?? TRANSLATIONS.en[key];
}

export function loadSavedLocale(): AppLocale {
  if (typeof globalThis.localStorage === 'undefined') return 'en';
  try {
    const raw = globalThis.localStorage.getItem(LOCALE_STORAGE_KEY);
    return raw === 'vi' ? 'vi' : 'en';
  } catch {
    return 'en';
  }
}

export function saveLocale(locale: AppLocale): void {
  if (typeof globalThis.localStorage === 'undefined') return;
  try {
    globalThis.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Ignore storage errors
  }
}
